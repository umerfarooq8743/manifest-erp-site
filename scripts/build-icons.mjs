const symbols = Object.entries(ICONS).map(([name, component]) => {
  const Comp = lucide[component];
  if (!Comp) throw new Error(`Unknown Lucide icon: ${component} (${name})`);
  const markup = renderToStaticMarkup(createElement(Comp));
  const inner = markup.slice(markup.indexOf(">") + 1, markup.lastIndexOf("</svg>"));
  if (!inner.trim()) throw new Error(`Empty icon: ${component}`);
  return `<symbol id="${name}" viewBox="0 0 24 24">${inner}</symbol>`;
});

const sprite = `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join("")}</svg>\n`;
const version = createHash("sha256").update(sprite).digest("hex").slice(0, 10);
writeFileSync("public/icons/sprite.svg", sprite);

const names = Object.keys(ICONS);
writeFileSync(
  "src/components/ui/icon-names.ts",
  `// Generated by scripts/build-icons.mjs — do not edit by hand. Run \`npm run icons\`.\n` +
    `export const ICON_NAMES = ${JSON.stringify(names, null, 2)} as const;\n\n` +
    `export type IconName = (typeof ICON_NAMES)[number];\n\n` +
    `/** Changes whenever the sprite changes, so browsers fetch the new file. */\n` +
    `export const ICON_SPRITE = "/icons/sprite.svg?v=${version}";\n`,
);
console.log(`sprite: ${names.length} icons, ${sprite.length} bytes, version ${version}`);
